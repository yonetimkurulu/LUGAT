async function seedMoreRoots() {
  console.log("🌱 18 Yeni Kök ve Kelime Ailesi Veritabanına Ekleniyor...");

  let rootCount = 0;
  let wordCount = 0;

  for (const rootItem of additionalRoots) {
    const root = await prisma.root.upsert({
      where: { slug: rootItem.slug },
      update: {
        rootLettersModern: rootItem.rootLettersModern,
        rootLettersArabic: rootItem.rootLettersArabic,
        origin: rootItem.origin,
        primaryMeaning: rootItem.primaryMeaning,
        description: rootItem.description,
      },
      create: {
        slug: rootItem.slug,
        rootLettersModern: rootItem.rootLettersModern,
        rootLettersArabic: rootItem.rootLettersArabic,
        origin: rootItem.origin,
        primaryMeaning: rootItem.primaryMeaning,
        description: rootItem.description,
      },
    });

    rootCount++;

    for (let i = 0; i < rootItem.words.length; i++) {
      const w = rootItem.words[i];
      await prisma.word.upsert({
        where: { slug: w.slug },
        update: {
          modernTurkish: w.modernTurkish,
          modernEquivalents: w.modernEquivalents,
          transliteration: w.transliteration,
          primaryOttoman: w.primaryOttoman,
          origin: w.origin,
          originDetail: w.originDetail,
          partOfSpeech: w.partOfSpeech,
          verificationStatus: "VERIFIED",
        },
        create: {
          slug: w.slug,
          modernTurkish: w.modernTurkish,
          modernEquivalents: w.modernEquivalents,
          transliteration: w.transliteration,
          primaryOttoman: w.primaryOttoman,
          origin: w.origin,
          originDetail: w.originDetail,
          partOfSpeech: w.partOfSpeech,
          verificationStatus: "VERIFIED",
          linguisticNotes: `${rootItem.rootLettersModern} kökünden türetilmiş asli Osmanlıca kelime.`,
          meanings: {
            create: {
              orderIndex: 1,
              definition: w.meaning,
              register: "Genel",
            },
          },
          spellings: {
            create: {
              arabicScript: w.primaryOttoman,
              spellingType: "Klasik İmla",
            },
          },
          examples: w.quote
            ? {
                create: {
                  sentenceModern: w.quote,
                  sentenceOttoman: w.primaryOttoman,
                },
              }
            : undefined,
          rootRelations: {
            create: {
              rootId: root.id,
              morphologicalPattern: w.pattern,
              morphologicalType: w.type,
              meaningContribution: w.meaning,
              orderIndex: i + 1,
            },
          },
        },
      });

      wordCount++;
    }
  }

  console.log(`✅ ${rootCount} yeni kök ve ${wordCount} kelime başarıyla eklendi!`);
  const totalRoots = await prisma.root.count();
  const totalWords = await prisma.word.count();
  console.log(`📊 Güncel Kök Sayısı: ${totalRoots}`);
  console.log(`📚 Güncel Kelime Sayısı: ${totalWords}`);
}

module.exports = { additionalRoots, seedMoreRoots };

if (require.main === module) {
  seedMoreRoots()
    .catch(console.error)
    .finally(() => prisma.$disconnect());
}
